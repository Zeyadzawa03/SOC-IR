// ── Checklist Renderer ───────────────────────────────────────
function renderChecklist(checks) {
  if (!checks) return '';
  return `<div class="det-checklist-inner">
    <div class="det-checklist-title">🔎 Validation Checklist</div>
    <div class="det-checklist-grid">
      ${Object.entries(checks).map(([k, c]) => `
      <div class="det-check-item ${c.passed?'check-pass':'check-fail'}">
        <span class="det-check-icon">${c.passed?'✅':'❌'}</span>
        <div>
          <div class="det-check-label">${escHTml(c.label)}</div>
          <div class="det-check-detail">${escHTml(c.detail)}</div>
        </div>
      </div>`).join('')}
    </div>
  </div>`;
}
function escHTml(s) { return String(s||'').replace(/[&<>"']/g, c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c])); }

// ── Rule Expand Toggle ───────────────────────────────────────
window.toggleRuleExpand = function(ruleId) {
  const body = document.getElementById('body-' + ruleId);
  const icon = document.getElementById('exp-' + ruleId);
  if (!body) return;
  const open = body.style.display !== 'none';
  body.style.display = open ? 'none' : 'block';
  if (icon) icon.textContent = open ? '▶' : '▼';
};

// ── Run Single Test ──────────────────────────────────────────
window.runSingleTest = function(testId, ruleId) {
  const rule = typeof SIGMA_RULES !== 'undefined' ? SIGMA_RULES.find(r => r.id === ruleId) : null;
  if (!rule) return;
  const testCases = getTestCasesForRule(rule);
  const tc = testCases.find(t => t.id === testId);
  if (!tc) return;

  const btn = document.getElementById('run-btn-' + testId);
  if (btn) { btn.textContent = '⏳'; btn.disabled = true; }

  setTimeout(() => {
    const result = DetectionValidator.runTestCase(tc, rule);
    // Update checklist
    const checklistEl = document.getElementById('checklist-' + testId);
    if (checklistEl) {
      checklistEl.innerHTML = renderChecklist(result.checks);
      checklistEl.style.display = 'block';
    }
    // Update status badge in tc header
    const tcEl = document.getElementById('tc-' + testId);
    if (tcEl) {
      const oldBadge = tcEl.querySelector('.det-status-badge');
      if (oldBadge) oldBadge.outerHTML = statusBadgeHtml(result.status, true);
    }
    // Update rule row status
    updateRuleRowStatus(ruleId);
    // Restore button
    if (btn) { btn.textContent = '▶ Run'; btn.disabled = false; }
  }, 600);
};

// ── Run All Tests for a Rule ─────────────────────────────────
window.runRuleTests = function(ruleId) {
  const rule = typeof SIGMA_RULES !== 'undefined' ? SIGMA_RULES.find(r => r.id === ruleId) : null;
  if (!rule) return;
  const btn = document.getElementById('run-rule-' + ruleId);
  if (btn) { btn.textContent = '⏳'; btn.disabled = true; }

  // Open the rule row
  const body = document.getElementById('body-' + ruleId);
  const icon = document.getElementById('exp-' + ruleId);
  if (body) { body.style.display = 'block'; }
  if (icon) { icon.textContent = '▼'; }

  const tcs = getTestCasesForRule(rule);
  let i = 0;
  function runNext() {
    if (i >= tcs.length) {
      if (btn) { btn.textContent = '▶ Run Tests'; btn.disabled = false; }
      updateRuleRowStatus(ruleId);
      updateGlobalStats();
      return;
    }
    const tc = tcs[i++];
    const result = DetectionValidator.runTestCase(tc, rule);
    const checklistEl = document.getElementById('checklist-' + tc.id);
    const tcEl = document.getElementById('tc-' + tc.id);
    if (checklistEl) { checklistEl.innerHTML = renderChecklist(result.checks); checklistEl.style.display = 'block'; }
    if (tcEl) {
      const oldBadge = tcEl.querySelector('.det-status-badge');
      if (oldBadge) oldBadge.outerHTML = statusBadgeHtml(result.status, true);
    }
    setTimeout(runNext, 200);
  }
  runNext();
};

// ── Run ALL Tests (all rules) ────────────────────────────────
window.runAllDetectionTests = function() {
  const rules = typeof SIGMA_RULES !== 'undefined' ? SIGMA_RULES : [];
  const btn = document.getElementById('runAllBtn');
  const prog = document.getElementById('det-progress-bar');
  const progFill = document.getElementById('det-progress-fill');
  const progLabel = document.getElementById('det-progress-label');
  if (btn) { btn.textContent = '⏳ Running...'; btn.disabled = true; }
  if (prog) prog.style.display = 'block';

  let i = 0;
  function runNext() {
    if (i >= rules.length) {
      if (btn) { btn.textContent = '▶ Run All Tests'; btn.disabled = false; }
      if (prog) prog.style.display = 'none';
      updateGlobalStats();
      if (typeof showToast === 'function') showToast(`All ${rules.length} rules validated`, 'success');
      return;
    }
    const rule = rules[i];
    const pct = Math.round(((i+1)/rules.length)*100);
    if (progFill) progFill.style.width = pct + '%';
    if (progLabel) progLabel.textContent = `Validating: ${rule.title} (${i+1}/${rules.length})`;
    DetectionValidator.runRuleTests(rule);
    updateRuleRowStatus(rule.id);
    i++;
    setTimeout(runNext, 10);
  }
  runNext();
};


// ── Filter Rules ─────────────────────────────────────────────
window.filterDetectionTests = function() {
  const search = (document.getElementById('detSearchInput')?.value || '').toLowerCase();
  const cat    = document.getElementById('detCatFilter')?.value || 'all';
  const status = document.getElementById('detStatusFilter')?.value || 'all';
  const type   = document.getElementById('detTypeFilter')?.value || 'all';

  const rules = typeof SIGMA_RULES !== 'undefined' ? SIGMA_RULES : [];
  let visible = 0;

  rules.forEach(rule => {
    const row = document.getElementById('rule-row-' + rule.id);
    if (!row) return;

    // Category filter
    if (cat !== 'all' && rule.category !== cat) { row.style.display = 'none'; return; }

    // Search filter
    if (search) {
      const haystack = `${rule.title} ${rule.techniqueId} ${rule.category} ${rule.description}`.toLowerCase();
      if (!haystack.includes(search)) { row.style.display = 'none'; return; }
    }

    // Status filter
    if (status !== 'all') {
      const tcs = getTestCasesForRule(rule);
      const statuses = tcs.map(tc => ValidationStateManager.getStatus(tc.id));
      const rStatus = statuses.every(s=>s==='passed') ? 'passed'
                    : statuses.some(s=>s==='failed')  ? 'failed'
                    : statuses.every(s=>s==='not_tested') ? 'not_tested'
                    : 'needs_review';
      if (rStatus !== status) { row.style.display = 'none'; return; }
    }

    row.style.display = 'block';
    visible++;
  });

  const countEl = document.getElementById('det-rule-count');
  if (countEl) countEl.textContent = `Showing ${visible} of ${rules.length} rules`;
  const emptyEl = document.getElementById('det-empty-state');
  if (emptyEl) emptyEl.style.display = visible === 0 ? 'block' : 'none';
};

window.filterByCategory = function(cat) {
  const sel = document.getElementById('detCatFilter');
  if (sel) { sel.value = cat; filterDetectionTests(); }
};

// ── Update Rule Row Status After Test ────────────────────────
function updateRuleRowStatus(ruleId) {
  const rule = typeof SIGMA_RULES !== 'undefined' ? SIGMA_RULES.find(r=>r.id===ruleId) : null;
  if (!rule) return;
  const tcs = getTestCasesForRule(rule);
  const statuses = tcs.map(tc => ValidationStateManager.getStatus(tc.id));
  const rPassed = statuses.filter(s=>s==='passed').length;
  const rAll    = statuses.length;
  const rStatus = statuses.every(s=>s==='passed') ? 'passed'
                : statuses.some(s=>s==='failed')  ? 'failed'
                : statuses.every(s=>s==='not_tested') ? 'not_tested' : 'needs_review';
  const row = document.getElementById('rule-row-' + ruleId);
  if (!row) return;
  const countEl = row.querySelector('.det-tc-count');
  if (countEl) countEl.textContent = `${rPassed}/${rAll} tests`;
  const oldBadge = row.querySelector('.det-rule-right .det-status-badge');
  if (oldBadge) oldBadge.outerHTML = statusBadgeHtml(rStatus, true);
}

// ── Update Global Stats ──────────────────────────────────────
function updateGlobalStats() {
  const s = getGlobalTestStats();
  const pr = s.total > 0 ? Math.round((s.passed/s.total)*100) : 0;
  const setEl = (id, v) => { const el = document.getElementById(id); if(el) el.textContent = v; };
  // We re-navigate to refresh (lightweight approach)
  // Stats cards are in static HTML rendered at page load, refresh them:
  document.querySelectorAll('.det-stat-num').forEach((el, i) => {
    const vals = [s.total, s.passed, s.failed, s.needsReview, s.notTested, pr+'%'];
    if (vals[i] !== undefined) el.textContent = vals[i];
  });
}

// ── Status Badge Helper (standalone) ────────────────────────
function statusBadgeHtml(status, small) {
  const cfg = {
    passed:       { icon:'✅', label:'Passed',       cls:'det-status-passed'   },
    failed:       { icon:'❌', label:'Failed',       cls:'det-status-failed'   },
    needs_review: { icon:'⚠️', label:'Needs Review', cls:'det-status-review'   },
    not_tested:   { icon:'⬜', label:'Not Tested',   cls:'det-status-untested' }
  };
  const c = cfg[status] || cfg.not_tested;
  return `<span class="det-status-badge ${c.cls}${small?' det-status-sm':''}">${c.icon} ${c.label}</span>`;
}

